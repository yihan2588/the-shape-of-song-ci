"""Audit the user-selected endpoint imagery against content-only map regions."""
import hashlib
import json
import re
from pathlib import Path
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
WORDS = [['万里', '千古', '白发'], ['黄昏', '相思', '落花']]

def build():
    atlas = json.loads((ROOT/'data/atlas.json').read_text())
    docs = atlas['documents']
    texts = [d['text'] for d in docs]
    han = [len(re.findall(r'[\u3400-\u9fff]', text)) for text in texts]
    views = {}
    for name, coordinates in atlas['coordinates'].items():
        xy = np.array(coordinates)
        center = xy.mean(axis=0)
        _, singular, basis = np.linalg.svd(xy-center, full_matrices=False)
        direction = basis[0] * (1 if basis[0, 0] >= 0 else -1)
        order = np.argsort((xy-center)@direction, kind='stable')
        regions = []
        for end, words in enumerate(WORDS):
            evidence = []
            for fraction in [.2, .25, .3]:
                n = round(len(docs)*fraction)
                tails = [order[:n], order[-n:]]
                a, b = tails[end], tails[1-end]
                counts = []
                for word in words:
                    counts.append({'bigram': word,
                        'poems': sum(word in texts[i] for i in a),
                        'opposite_poems': sum(word in texts[i] for i in b),
                        'per_1000_han': 1000*sum(texts[i].count(word) for i in a)/sum(han[i] for i in a),
                        'opposite_per_1000_han': 1000*sum(texts[i].count(word) for i in b)/sum(han[i] for i in b)})
                evidence.append({'fraction': fraction, 'poems_per_end': n, 'counts': counts})
            regions.append({'words': words, 'evidence': evidence,
                'poem_ids': [docs[i]['id'] for i in (order[:60] if end == 0 else order[-60:])]})
        views[name] = {'direction': direction.tolist(),
            'displayed_variance_fraction': float(singular[0]**2/(singular**2).sum()),
            'horizons_at_top': bool(direction[1] < 0), 'regions': regions}
    return {'method': 'First principal direction of each saved 2D projection, oriented toward increasing x. The outer 25% at either end (60 poems each) supply document-frequency contrasts. 20% and 30% tails and occurrences per 1000 Han characters check sensitivity. Only complete poem text is counted; no poet or style labels are used.',
        'selection': 'The same two imagery triplets were chosen by the user for both views after review of distinctive bigrams. They are literary landmarks along a continuous projection gradient, not a fitted classification or a claim about preserved original-space distances.',
        'poems': len(docs), 'content_sha256': hashlib.sha256(json.dumps(texts, ensure_ascii=False).encode()).hexdigest(),
        'views': views}

def main():
    result = build()
    (ROOT/'data/axis-imagery.json').write_text(json.dumps(result, ensure_ascii=False, indent=2)+'\n')
    public = {name: {'horizons_at_top': v['horizons_at_top'],
        'displayed_variance_fraction': v['displayed_variance_fraction'],
        'ends': [{'words': r['words'], 'counts': r['evidence'][1]['counts']} for r in v['regions']]}
        for name, v in result['views'].items()}
    (ROOT/'public/axis-imagery.js').write_text('// Generated by scripts/prepare_imagery.py from the fixed map and poem text.\nwindow.SONG_CI_IMAGERY = '+json.dumps(public, ensure_ascii=False, separators=(',', ':'))+';\n')

if __name__ == '__main__':
    main()
